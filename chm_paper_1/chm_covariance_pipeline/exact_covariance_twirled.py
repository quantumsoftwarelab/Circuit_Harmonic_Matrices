#!/usr/bin/env python3
"""
Exact coefficient-covariance propagation without enumerating C columns.

This script computes the parameter-averaged Fourier-coefficient covariance

    Cov[a_omega, a_omega']

for PQCs with commuting Pauli encoders and Pauli/controlled-rotation trainer
blocks.  It does *not* build the full circuit harmonic matrix C.  Instead it
uses the identity

    Cov[a] = C P C^dagger

and evaluates the quadratic form directly by a two-copy, parameter-twirled
Heisenberg propagation.  This avoids storing the exponentially large k-support.

The method is exact for Pauli rotations under uniform parameter averaging.  For
controlled RX/RZ gates it uses deterministic Fourier quadrature of the local
2-qubit twirl map; with a sufficient number of quadrature points this is exact
up to floating point error for the trigonometric polynomial generated by the
controlled rotation.

Typical use:

    python exact_covariance_twirled.py \
        --out_dir exact_cov/CIRCUIT_18_n6d4 \
        --ansatz CIRCUIT_18 --n_qubits 6 --train_depth 4 \
        --encoder_axis RX --obs_kind OZ \
        --combine_tol 1e-14 --progress

Optional Monte Carlo validation against ansatze.py/PennyLane:

    python exact_covariance_twirled.py ... \
        --ansatze_path /path/to/repo_or_module_dir \
        --validate_mc_samples 4096 --n_x_mc 128

Important convention:
    The standard Pauli rotations are 2*pi-periodic at the expectation-value
    level.  PennyLane CRX/CRZ gates can generate half-angle terms; if you want
    their full parameter-torus periodicity, use --theta_period 4pi.  If your MC
    code samples theta in [0,2*pi), leave the default --theta_period 2pi so the
    exact average matches that ensemble.
"""

