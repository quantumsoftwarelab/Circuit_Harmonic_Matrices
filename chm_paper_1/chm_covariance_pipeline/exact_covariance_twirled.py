# Two-copy second-moment propagation
# ---------------------------------------------------------------------------


def theta_average_pair_pauli(p1: int, p2: int, coeff: complex, om1: int, om2: int, op: Operation, n: int) -> List[Tuple[int, int, complex, int, int]]:
    assert op.pauli is not None
    P = op.pauli
    a1 = not commute(P, p1, n)
    a2 = not commute(P, p2, n)
    if not a1 and not a2:
        return [(p1, p2, coeff, om1, om2)]
    if a1 != a2:
        # One side has cos/sin and the other is constant; the parameter average is zero.
        return []
    # both anticommute: average cos^2 and sin^2 survive.
    ph1, r1 = pauli_mul(P, p1, n)
    ph2, r2 = pauli_mul(P, p2, n)
    coscos = coeff * 0.5
    sinsin = coeff * (1j * ph1) * (1j * ph2) * 0.5
    return [(p1, p2, coscos, om1, om2), (r1, r2, sinsin, om1, om2)]


def branch_x_pair_one_copy(p1: int, p2: int, coeff: complex, om1: int, om2: int, op: Operation, n: int, copy: int) -> List[Tuple[int, int, complex, int, int]]:
    if copy == 1:
        branches = branch_x_single(p1, coeff, om1, op, n)
        return [(q1, p2, c, qom, om2) for q1, c, qom in branches]
    branches = branch_x_single(p2, coeff, om2, op, n)
    return [(p1, q2, c, om1, qom) for q2, c, qom in branches]


def apply_pair_clifford(p1: int, p2: int, coeff: complex, om1: int, om2: int, op: Operation, n: int) -> Tuple[int, int, complex, int, int]:
    if op.kind == "cnot":
        ph1, q1 = conjugate_by_cnot(p1, n, op.wires[0], op.wires[1])
        ph2, q2 = conjugate_by_cnot(p2, n, op.wires[0], op.wires[1])
    elif op.kind == "cz":
        ph1, q1 = conjugate_by_cz(p1, n, op.wires[0], op.wires[1])
        ph2, q2 = conjugate_by_cz(p2, n, op.wires[0], op.wires[1])
    else:
        raise ValueError(op.kind)
    return q1, q2, coeff * ph1 * ph2, om1, om2


def exact_second_moment(ops: Sequence[Operation], obs: Sequence[Tuple[complex, int]], n: int, cr_pair_maps: Dict[str, List[List[Tuple[int, int, complex]]]], tol: float, max_states: int, progress: bool) -> Tuple[Dict[Tuple[int, int], complex], PairState]:
    state: PairState = {}
    for c1, p1 in obs:
        for c2, p2 in obs:
            add_acc(state, (p1, p2, 0, 0), complex(c1) * complex(c2), tol)
    t0 = time.time()
    last_report_t = t0
    last_report_step = 0
    last_report_states = max(1, len(state))
    for step, op in enumerate(reversed(ops), start=1):
        new: PairState = {}
        for (p1, p2, om1, om2), c in state.items():
            if op.kind == "rot" and op.var_kind == "x":
                # U(x) on copy 1 and U(y) on copy 2, with independent Fourier variables.
                tmp = branch_x_pair_one_copy(p1, p2, c, om1, om2, op, n, copy=1)
                for q1, q2, ctmp, qom1, qom2 in tmp:
                    for r1, r2, c2, rom1, rom2 in branch_x_pair_one_copy(q1, q2, ctmp, qom1, qom2, op, n, copy=2):
                        add_acc(new, (r1, r2, rom1, rom2), c2, tol)
            elif op.kind == "rot" and op.var_kind == "theta":
                for q1, q2, c2, qom1, qom2 in theta_average_pair_pauli(p1, p2, c, om1, om2, op, n):
                    add_acc(new, (q1, q2, qom1, qom2), c2, tol)
            elif op.kind in ("cnot", "cz"):
                q1, q2, c2, qom1, qom2 = apply_pair_clifford(p1, p2, c, om1, om2, op, n)
                add_acc(new, (q1, q2, qom1, qom2), c2, tol)
            elif op.kind == "cr":
                axis = str(op.axis)
                control, target = op.wires
                lin1 = local_index_2q(p1, control, target)
                lin2 = local_index_2q(p2, control, target)
                for lout1, lout2, fac in cr_pair_maps[axis][lin1 * 16 + lin2]:
                    q1 = set_local_2q(p1, control, target, lout1)
                    q2 = set_local_2q(p2, control, target, lout2)
                    add_acc(new, (q1, q2, om1, om2), c * fac, tol)
            else:
                raise ValueError(op)
        state = new
        if len(state) > max_states:
            raise RuntimeError(f"Second-moment propagation exceeded --max_states={max_states} at step {step}; current states={len(state)}")
        if progress and (step == 1 or step == len(ops) or step % 5 == 0):
            last_report_t, last_report_step, last_report_states = _print_step_progress(
                "pair", step, len(ops), len(state), t0,
                last_report_t, last_report_step, last_report_states,
            )
    moment: Dict[Tuple[int, int], complex] = defaultdict(complex)
    terminal: PairState = {}
    for (p1, p2, om1, om2), c in state.items():
        e1 = input_expectation_zero(p1, n)
        e2 = input_expectation_zero(p2, n)
        if abs(e1) > 0 and abs(e2) > 0:
            val = c * e1 * e2
            moment[(int(om1), int(om2))] += val
            terminal[(p1, p2, om1, om2)] = val
    return dict(moment), terminal


