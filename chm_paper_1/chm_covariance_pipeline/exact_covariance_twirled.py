# I=0, X=1, Y=2, Z=3, encoded in two bits per qubit.
I, X, Y, Z = 0, 1, 2, 3
CHAR_TO_CODE = {"I": I, "X": X, "Y": Y, "Z": Z}
CODE_TO_CHAR = {v: k for k, v in CHAR_TO_CODE.items()}

# (phase, product)
_MUL = {
    (I, I): (1+0j, I), (I, X): (1+0j, X), (I, Y): (1+0j, Y), (I, Z): (1+0j, Z),
    (X, I): (1+0j, X), (Y, I): (1+0j, Y), (Z, I): (1+0j, Z),
    (X, X): (1+0j, I), (Y, Y): (1+0j, I), (Z, Z): (1+0j, I),
    (X, Y): (1j, Z),  (Y, Z): (1j, X),  (Z, X): (1j, Y),
    (Y, X): (-1j, Z), (Z, Y): (-1j, X), (X, Z): (-1j, Y),
}


def get_code(p: int, q: int) -> int:
    return (int(p) >> (2 * int(q))) & 0b11


def set_code(p: int, q: int, code: int) -> int:
    q = int(q)
    mask = 0b11 << (2 * q)
    return (int(p) & ~mask) | ((int(code) & 0b11) << (2 * q))


def pauli_on(n: int, axis: str, wire: int) -> int:
    code = CHAR_TO_CODE[axis[-1] if axis.startswith("R") else axis]
    return set_code(0, wire, code)


def pauli_zz(n: int, a: int, b: int) -> int:
    return set_code(set_code(0, a, Z), b, Z)


def pauli_to_str(p: int, n: int) -> str:
    return "".join(CODE_TO_CHAR[get_code(p, q)] for q in range(n))


def local_index_2q(p: int, a: int, b: int) -> int:
    return get_code(p, a) + 4 * get_code(p, b)


def set_local_2q(p: int, a: int, b: int, local_idx: int) -> int:
    c0 = int(local_idx) % 4
    c1 = int(local_idx) // 4
    return set_code(set_code(p, a, c0), b, c1)


def commute(p: int, q: int, n: int) -> bool:
    anti = 0
    for w in range(n):
        a = get_code(p, w)
        b = get_code(q, w)
        if a != I and b != I and a != b:
            anti += 1
    return (anti % 2) == 0


def pauli_mul(p: int, q: int, n: int) -> Tuple[complex, int]:
    phase = 1 + 0j
    out = 0
    for w in range(n):
        ph, c = _MUL[(get_code(p, w), get_code(q, w))]
        phase *= ph
        out = set_code(out, w, c)
    return phase, out


def input_expectation_zero(p: int, n: int) -> complex:
    for w in range(n):
        c = get_code(p, w)
        if c not in (I, Z):
            return 0 + 0j
    return 1 + 0j


# ---------------------------------------------------------------------------
# Clifford conjugation in packed representation
# ---------------------------------------------------------------------------


def conjugate_by_cnot(q: int, n: int, control: int, target: int) -> Tuple[complex, int]:
    acc = 0
    coeff = 1 + 0j
    for w in range(n):
        ch = get_code(q, w)
        if ch == I:
            continue
        img = 0
        if w == control:
            if ch == X:
                img = set_code(set_code(0, control, X), target, X)
            elif ch == Y:
                img = set_code(set_code(0, control, Y), target, X)
            elif ch == Z:
                img = set_code(0, control, Z)
        elif w == target:
            if ch == X:
                img = set_code(0, target, X)
            elif ch == Y:
                img = set_code(set_code(0, control, Z), target, Y)
            elif ch == Z:
                img = set_code(set_code(0, control, Z), target, Z)
        else:
            img = set_code(0, w, ch)
        ph, acc = pauli_mul(acc, img, n)
        coeff *= ph
    return coeff, acc


def conjugate_by_cz(q: int, n: int, a: int, b: int) -> Tuple[complex, int]:
    acc = 0
    coeff = 1 + 0j
    for w in range(n):
        ch = get_code(q, w)
        if ch == I:
            continue
        img = 0
        if w == a:
            if ch == X:
                img = set_code(set_code(0, a, X), b, Z)
            elif ch == Y:
                img = set_code(set_code(0, a, Y), b, Z)
            elif ch == Z:
                img = set_code(0, a, Z)
        elif w == b:
            if ch == X:
                img = set_code(set_code(0, a, Z), b, X)
            elif ch == Y:
                img = set_code(set_code(0, a, Z), b, Y)
            elif ch == Z:
                img = set_code(0, b, Z)
        else:
            img = set_code(0, w, ch)
        ph, acc = pauli_mul(acc, img, n)
        coeff *= ph
    return coeff, acc


