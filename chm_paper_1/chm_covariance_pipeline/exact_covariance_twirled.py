def main(argv: Optional[Sequence[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    p.add_argument("--out_dir", required=True)
    p.add_argument("--ansatz", required=True)
    p.add_argument("--n_qubits", type=int, required=True)
    p.add_argument("--n_layers", type=int, default=1)
    p.add_argument("--train_depth", type=int, required=True)
    p.add_argument("--encoder_axis", default="RX", choices=["RX", "RY", "RZ"])
    p.add_argument("--encoder_scale", default="1")
    p.add_argument("--obs_kind", default="OZ", choices=["OX", "OY", "OZ", "OZZ"])
    p.add_argument("--theta_period", default="2pi", help="Parameter averaging interval length. Use 4pi for full PennyLane CRX/CRZ unitary periodicity.")
    p.add_argument("--cr_quadrature_points", type=int, default=64)
    p.add_argument("--combine_tol", type=float, default=1e-14)
    p.add_argument("--max_states", type=int, default=20_000_000)
    p.add_argument("--progress", action="store_true")
    p.add_argument("--ansatze_path", default=None)
    p.add_argument("--validate_mc_samples", type=int, default=0)
    p.add_argument("--n_x_mc", type=int, default=128)
    p.add_argument("--mc_batch_size", type=int, default=32)
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args(argv)

    out_dir = Path(args.out_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    t0 = time.time()
    encoder_scale = int(round(float(args.encoder_scale)))
    if abs(float(args.encoder_scale) - encoder_scale) > 1e-12:
        raise ValueError("This script currently requires integer encoder_scale")
    theta_period = parse_period(args.theta_period)

    ops, m = build_forward_ops(args.ansatz, args.n_qubits, args.n_layers, args.train_depth, args.encoder_axis, encoder_scale)
    obs = observable_terms(args.n_qubits, args.obs_kind, args.ansatz)

    # Precompute controlled-rotation maps only if needed.
    cr_axes = sorted({op.axis for op in ops if op.kind == "cr" and op.axis is not None})
    cr_single_maps: Dict[str, List[List[Tuple[int, complex]]]] = {}
    cr_pair_maps: Dict[str, List[List[Tuple[int, int, complex]]]] = {}
    for axis in cr_axes:
        if args.progress:
            print(f"precomputing CR{axis[-1]} twirl maps with {args.cr_quadrature_points} points over period {theta_period}", flush=True)
        smap, pmap = build_cr_maps(str(axis), int(args.cr_quadrature_points), theta_period, float(args.combine_tol))
        cr_single_maps[str(axis)] = smap
        cr_pair_maps[str(axis)] = pmap

    if args.progress:
        print(f"built circuit: ansatz={args.ansatz} n={args.n_qubits} L={args.n_layers} d={args.train_depth} m={m} ops={len(ops)}", flush=True)

    mean_omegas, mean_vals_small, mean_terminal = exact_mean(ops, obs, args.n_qubits, cr_single_maps, float(args.combine_tol), int(args.max_states), bool(args.progress))
    mean_dict = {int(o): complex(v) for o, v in zip(mean_omegas.tolist(), mean_vals_small.tolist())}
    moment, second_terminal = exact_second_moment(ops, obs, args.n_qubits, cr_pair_maps, float(args.combine_tol), int(args.max_states), bool(args.progress))
    omegas, mean, second_raw, second_conj, Cov = assemble_matrices(mean_dict, moment)
    Corr = corr_from_cov(Cov)

    save_matrix_csv(out_dir / "exact_covariance.csv", omegas, Cov)
    save_matrix_csv(out_dir / "exact_correlation.csv", omegas, Corr)
    np.savez_compressed(
        out_dir / "exact_twirled_covariance.npz",
        omegas=omegas,
        mean=mean,
        second_raw=second_raw,
        second_conj=second_conj,
        Cov=Cov,
        Corr=Corr,
    )
    plots = make_plots(out_dir, omegas, Cov, Corr, mean, f"{args.ansatz}, n={args.n_qubits}, L={args.n_layers}, d={args.train_depth}")
    mc_validation = validate_mc(args, omegas, Cov, mean, out_dir)

    summary = {
        "created_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "ansatz": args.ansatz,
        "n_qubits": int(args.n_qubits),
        "n_layers": int(args.n_layers),
        "train_depth": int(args.train_depth),
        "encoder_axis": args.encoder_axis,
        "encoder_scale": args.encoder_scale,
        "obs_kind": args.obs_kind,
        "theta_period": args.theta_period,
        "theta_period_float": theta_period,
        "m_parameters": int(m),
        "n_forward_ops": int(len(ops)),
        "n_observable_terms": int(len(obs)),
        "n_mean_terminal_terms": int(len(mean_terminal)),
        "n_second_terminal_terms": int(len(second_terminal)),
        "n_second_moment_entries": int(len(moment)),
        "n_omega": int(len(omegas)),
        "omega_min": int(np.min(omegas)) if len(omegas) else None,
        "omega_max": int(np.max(omegas)) if len(omegas) else None,
        "cov_frobenius_norm": float(np.linalg.norm(Cov)),
        "corr_offdiag_ratio": offdiag_ratio(Corr),
        "cov_offdiag_ratio": offdiag_ratio(Cov),
        "cov_effective_rank": effective_rank_psd(Cov),
        "runtime_seconds": float(time.time() - t0),
        "cr_axes": cr_axes,
        "cr_quadrature_points": int(args.cr_quadrature_points),
        "mc_validation": mc_validation,
        "plots": plots,
        "outputs": {
            "npz": "exact_twirled_covariance.npz",
            "covariance_csv": "exact_covariance.csv",
            "correlation_csv": "exact_correlation.csv",
            "summary_plot": "exact_covariance_summary.png" if "exact_covariance_summary.png" in plots else None,
            "covariance_heatmap": "cov_real_heatmap.png" if "cov_real_heatmap.png" in plots else None,
            "correlation_heatmap": "corr_abs_heatmap.png" if "corr_abs_heatmap.png" in plots else None,
            "mc_validation_npz": "mc_validation.npz" if mc_validation and mc_validation.get("status") == "ok" else None,
        },
        "method_note": "Exact two-copy parameter-twirled Heisenberg propagation computes C P C^dagger directly, avoiding explicit enumeration of k-columns.",
    }
    with open(out_dir / "manifest.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    with open(out_dir / "results_summary.txt", "w", encoding="utf-8") as f:
        f.write(json.dumps(summary, indent=2))
        f.write("\n")

    print(json.dumps(summary, indent=2))
    print(f"\nSaved exact twirled covariance outputs to: {out_dir}", flush=True)
    return 0


