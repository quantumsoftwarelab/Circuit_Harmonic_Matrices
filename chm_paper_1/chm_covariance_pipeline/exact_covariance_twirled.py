def observable_terms(n: int, obs_kind: str, ansatz: str) -> List[Tuple[complex, int]]:
    kind = "OZZ" if ansatz == "CIRCUIT_MULTIOBS" else obs_kind
    out: List[Tuple[complex, int]] = []
    if kind == "OX":
        for w in range(n):
            out.append((1.0 / n, pauli_on(n, "X", w)))
    elif kind == "OY":
        for w in range(n):
            out.append((1.0 / n, pauli_on(n, "Y", w)))
    elif kind == "OZ":
        for w in range(n):
            out.append((1.0 / n, pauli_on(n, "Z", w)))
    elif kind == "OZZ":
        pairs = [(i, j) for i in range(n) for j in range(i + 1, n)]
        if not pairs:
            out.append((1.0, pauli_on(n, "Z", 0)))
        else:
            scale = 2.0 / (n * (n - 1))
            for i, j in pairs:
                out.append((scale, pauli_zz(n, i, j)))
    else:
        raise ValueError(obs_kind)
    return out


# ---------------------------------------------------------------------------
# Controlled-rotation local maps by deterministic quadrature
# ---------------------------------------------------------------------------

_PAULI_1Q = [
    np.array([[1, 0], [0, 1]], dtype=np.complex128),
    np.array([[0, 1], [1, 0]], dtype=np.complex128),
    np.array([[0, -1j], [1j, 0]], dtype=np.complex128),
    np.array([[1, 0], [0, -1]], dtype=np.complex128),
]
_PAULI_2Q = [np.kron(_PAULI_1Q[i], _PAULI_1Q[j]) for j in range(4) for i in range(4)]
# local index = code_control + 4*code_target, matching kron(control, target)


def cr_unitary(axis: str, theta: float) -> np.ndarray:
    axis = str(axis).upper()
    if axis == "RZ":
        rz = np.array([[np.exp(-0.5j * theta), 0], [0, np.exp(0.5j * theta)]], dtype=np.complex128)
        U = np.eye(4, dtype=np.complex128)
        U[2:4, 2:4] = rz
        return U
    if axis == "RX":
        c = math.cos(theta / 2.0)
        s = math.sin(theta / 2.0)
        rx = np.array([[c, -1j * s], [-1j * s, c]], dtype=np.complex128)
        U = np.eye(4, dtype=np.complex128)
        U[2:4, 2:4] = rx
        return U
    raise ValueError(f"Unsupported controlled rotation axis: {axis}")


def single_cr_conj_coeffs(axis: str, theta: float) -> np.ndarray:
    """Return coeffs[in_local, out_local] for U^dag P_in U."""
    U = cr_unitary(axis, theta)
    Ud = U.conj().T
    coeffs = np.zeros((16, 16), dtype=np.complex128)
    for a, P in enumerate(_PAULI_2Q):
        M = Ud @ P @ U
        # Pauli basis is orthogonal: coeff = Tr(P_b M)/4.
        for b, B in enumerate(_PAULI_2Q):
            coeffs[a, b] = np.trace(B @ M) / 4.0
    return coeffs


def build_cr_maps(axis: str, n_quad: int, theta_period: float, tol: float) -> Tuple[List[List[Tuple[int, complex]]], List[List[Tuple[int, int, complex]]]]:
    """Build single-copy and two-copy averaged local maps for CR axis.

    single_map[a] = [(b, coeff_avg)] for E_theta[U^dag P_a U]
    pair_map[a*16+b] = [(a_out,b_out, coeff_avg)] for
        E_theta[(U^dag P_a U) tensor (U^dag P_b U)].
    """
    single_acc = np.zeros((16, 16), dtype=np.complex128)
    pair_acc = np.zeros((16, 16, 16, 16), dtype=np.complex128)
    for j in range(int(n_quad)):
        theta = theta_period * (j + 0.5) / float(n_quad)
        A = single_cr_conj_coeffs(axis, theta)
        single_acc += A
        # pair_acc[a,b,c,d] += A[a,c] * A[b,d]
        pair_acc += A[:, None, :, None] * A[None, :, None, :]
    single_acc /= float(n_quad)
    pair_acc /= float(n_quad)

    single_map: List[List[Tuple[int, complex]]] = []
    for a in range(16):
        entries = [(b, single_acc[a, b]) for b in range(16) if abs(single_acc[a, b]) > tol]
        single_map.append(entries)

    pair_map: List[List[Tuple[int, int, complex]]] = []
    for a in range(16):
        for b in range(16):
            entries = []
            for c in range(16):
                for d in range(16):
                    val = pair_acc[a, b, c, d]
                    if abs(val) > tol:
                        entries.append((c, d, val))
            pair_map.append(entries)
    return single_map, pair_map


# ---------------------------------------------------------------------------
# Single-copy mean propagation
# ---------------------------------------------------------------------------

SingleState = Dict[Tuple[int, int], complex]          # (pauli, omega) -> coeff
PairState = Dict[Tuple[int, int, int, int], complex]  # (pauli1, pauli2, om1, om2) -> coeff


def add_acc(acc: Dict[tuple, complex], key: tuple, val: complex, tol: float) -> None:
    if abs(val) <= tol:
        return
    new = acc.get(key, 0 + 0j) + val
    if abs(new) <= tol:
        acc.pop(key, None)
    else:
        acc[key] = new


def branch_x_single(p: int, coeff: complex, omega: int, op: Operation, n: int) -> List[Tuple[int, complex, int]]:
    assert op.pauli is not None
    P = op.pauli
    if commute(P, p, n):
        return [(p, coeff, omega)]
    out: List[Tuple[int, complex, int]] = []
    # cos branch
    for sgn, fac in ((+1, 0.5+0j), (-1, 0.5+0j)):
        out.append((p, coeff * fac, omega + sgn * int(op.omega_scale)))
    # sin branch: i P Q sin(x)
    ph, R = pauli_mul(P, p, n)
    base = coeff * 1j * ph
    for sgn, fac in ((+1, 1/(2j)), (-1, -1/(2j))):
        out.append((R, base * fac, omega + sgn * int(op.omega_scale)))
    return out


def theta_average_single_pauli(p: int, coeff: complex, omega: int, op: Operation, n: int) -> List[Tuple[int, complex, int]]:
    assert op.pauli is not None
    if commute(op.pauli, p, n):
        return [(p, coeff, omega)]
    # E[cos theta] = E[sin theta] = 0.
    return []


def apply_single_clifford(p: int, coeff: complex, omega: int, op: Operation, n: int) -> Tuple[int, complex, int]:
    if op.kind == "cnot":
        ph, q = conjugate_by_cnot(p, n, op.wires[0], op.wires[1])
    elif op.kind == "cz":
        ph, q = conjugate_by_cz(p, n, op.wires[0], op.wires[1])
    else:
        raise ValueError(op.kind)
    return q, coeff * ph, omega


def exact_mean(ops: Sequence[Operation], obs: Sequence[Tuple[complex, int]], n: int, cr_single_maps: Dict[str, List[List[Tuple[int, complex]]]], tol: float, max_states: int, progress: bool) -> Tuple[np.ndarray, np.ndarray, SingleState]:
    state: SingleState = {(p, 0): complex(c) for c, p in obs}
    t0 = time.time()
    last_report_t = t0
    last_report_step = 0
    last_report_states = max(1, len(state))
    for step, op in enumerate(reversed(ops), start=1):
        new: SingleState = {}
        for (p, om), c in state.items():
            if op.kind == "rot" and op.var_kind == "x":
                for p2, c2, om2 in branch_x_single(p, c, om, op, n):
                    add_acc(new, (p2, om2), c2, tol)
            elif op.kind == "rot" and op.var_kind == "theta":
                for p2, c2, om2 in theta_average_single_pauli(p, c, om, op, n):
                    add_acc(new, (p2, om2), c2, tol)
            elif op.kind in ("cnot", "cz"):
                p2, c2, om2 = apply_single_clifford(p, c, om, op, n)
                add_acc(new, (p2, om2), c2, tol)
            elif op.kind == "cr":
                axis = str(op.axis)
                control, target = op.wires
                lin = local_index_2q(p, control, target)
                for lout, fac in cr_single_maps[axis][lin]:
                    p2 = set_local_2q(p, control, target, lout)
                    add_acc(new, (p2, om), c * fac, tol)
            else:
                raise ValueError(op)
        state = new
        if len(state) > max_states:
            raise RuntimeError(f"Mean propagation exceeded --max_states={max_states} at step {step}; current states={len(state)}")
        if progress and (step == 1 or step == len(ops) or step % 5 == 0):
            last_report_t, last_report_step, last_report_states = _print_step_progress(
                "mean", step, len(ops), len(state), t0,
                last_report_t, last_report_step, last_report_states,
            )
    mean_dict: Dict[int, complex] = defaultdict(complex)
    terminal = {}
    for (p, om), c in state.items():
        e = input_expectation_zero(p, n)
        if abs(e) > 0:
            val = c * e
            mean_dict[int(om)] += val
            terminal[(p, om)] = val
    omegas = np.asarray(sorted(mean_dict), dtype=int)
    mean = np.asarray([mean_dict[int(o)] for o in omegas], dtype=np.complex128)
    return omegas, mean, terminal


