def _fmt_seconds(seconds: float) -> str:
    """Human-readable duration for progress/ETA messages."""
    if not np.isfinite(seconds) or seconds < 0:
        return "?"
    seconds = int(round(float(seconds)))
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    if h:
        return f"{h:d}h{m:02d}m{s:02d}s"
    if m:
        return f"{m:d}m{s:02d}s"
    return f"{s:d}s"


def _print_step_progress(
    label: str,
    step: int,
    total: int,
    states: int,
    t0: float,
    last_report_t: float,
    last_report_step: int,
    last_report_states: int,
) -> Tuple[float, int, int]:
    """Print elapsed time, a linear ETA, a recent-window ETA, and state growth.

    The recent-window ETA is deliberately labelled as an estimate only: for the
    two-copy propagation, future cost can change abruptly when the state
    dictionary starts growing or collapsing.
    """
    now = time.time()
    elapsed = now - t0
    remaining = max(0, int(total) - int(step))
    avg_eta = (elapsed / max(1, int(step))) * remaining
    recent_steps = max(1, int(step) - int(last_report_step))
    recent_eta = ((now - last_report_t) / recent_steps) * remaining
    growth = (float(states) / float(last_report_states)) if last_report_states > 0 else float("inf")
    growth_txt = "inf" if not np.isfinite(growth) else f"{growth:.2f}x"
    print(
        f"{label} step {step:4d}/{total} "
        f"states={states} growth={growth_txt} "
        f"elapsed={_fmt_seconds(elapsed)} "
        f"eta(avg)={_fmt_seconds(avg_eta)} eta(recent)={_fmt_seconds(recent_eta)}",
        flush=True,
    )
    return now, int(step), int(states)

