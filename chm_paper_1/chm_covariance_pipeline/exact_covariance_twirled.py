def assemble_matrices(mean_dict: Dict[int, complex], moment: Dict[Tuple[int, int], complex]) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    omega_set = set(mean_dict.keys())
    for om1, om2 in moment:
        omega_set.add(int(om1)); omega_set.add(int(om2)); omega_set.add(-int(om2))
    omegas = np.asarray(sorted(omega_set), dtype=int)
    idx = {int(o): i for i, o in enumerate(omegas.tolist())}
    mean = np.zeros(len(omegas), dtype=np.complex128)
    for om, c in mean_dict.items():
        mean[idx[int(om)]] = c
    second_raw = np.zeros((len(omegas), len(omegas)), dtype=np.complex128)
    for (om1, om2), c in moment.items():
        if int(om1) in idx and int(om2) in idx:
            second_raw[idx[int(om1)], idx[int(om2)]] = c
    # Desired covariance uses conjugated second index: E[a_omega conj(a_omega')]
    second_conj = np.zeros_like(second_raw)
    for om in omegas:
        for omp in omegas:
            second_conj[idx[int(om)], idx[int(omp)]] = moment.get((int(om), -int(omp)), 0 + 0j)
    Cov = second_conj - mean[:, None] * mean.conj()[None, :]
    # Numerical symmetrisation.
    Cov = 0.5 * (Cov + Cov.conj().T)
    return omegas, mean, second_raw, second_conj, Cov


def corr_from_cov(Cov: np.ndarray) -> np.ndarray:
    d = np.real(np.diag(Cov))
    denom = np.sqrt(np.maximum(d, 0.0))
    Corr = np.zeros_like(Cov)
    mask = denom > 1e-14
    Corr[np.ix_(mask, mask)] = Cov[np.ix_(mask, mask)] / np.outer(denom[mask], denom[mask])
    return Corr


def offdiag_ratio(A: np.ndarray) -> float:
    if A.size == 0 or A.shape[0] <= 1:
        return 0.0
    B = np.array(A, copy=True)
    np.fill_diagonal(B, 0)
    den = np.linalg.norm(A)
    return float(np.linalg.norm(B) / den) if den > 0 else 0.0


def effective_rank_psd(A: np.ndarray) -> float:
    if A.size == 0:
        return 0.0
    vals = np.linalg.eigvalsh(0.5 * (A + A.conj().T))
    vals = np.maximum(np.real(vals), 0.0)
    s1 = float(np.sum(vals)); s2 = float(np.sum(vals * vals))
    return (s1 * s1 / s2) if s2 > 0 else 0.0


def make_plots(out_dir: Path, omegas: np.ndarray, Cov: np.ndarray, Corr: np.ndarray, mean: np.ndarray, title: str) -> List[str]:
    made: List[str] = []
    if plt is None:
        return made

    def ticks(ax, axis: str) -> None:
        if len(omegas) <= 17:
            locs = np.arange(len(omegas)); labs = [str(int(o)) for o in omegas]
        else:
            locs = np.linspace(0, len(omegas) - 1, 9).round().astype(int); labs = [str(int(omegas[i])) for i in locs]
        if axis == "x":
            ax.set_xticks(locs, labs)
        else:
            ax.set_yticks(locs, labs)

    for arr, name, fname in [
        (np.real(Cov), r"$\operatorname{Re}\,\mathrm{Cov}[a_\omega,a_{\omega'}]$", "cov_real_heatmap.png"),
        (np.abs(Corr), r"$|\mathrm{Corr}[a_\omega,a_{\omega'}]|$", "corr_abs_heatmap.png"),
    ]:
        fig, ax = plt.subplots(figsize=(5.8, 5.1))
        im = ax.imshow(arr, origin="lower", aspect="equal")
        ax.set_title(name)
        ax.set_xlabel(r"actual $\omega'$"), ax.set_ylabel(r"actual $\omega$")
        ticks(ax, "x"); ticks(ax, "y")
        fig.colorbar(im, ax=ax, fraction=0.045, pad=0.04)
        fig.tight_layout(); fig.savefig(out_dir / fname, dpi=220); plt.close(fig)
        made.append(fname)

    fig, axes = plt.subplots(1, 3, figsize=(15.0, 4.2))
    axes[0].stem(omegas, np.real(np.diag(Cov)))
    axes[0].set_xlabel(r"$\omega$"); axes[0].set_ylabel(r"$\mathrm{Var}[a_\omega]$"); axes[0].set_title("Exact variance profile")
    im = axes[1].imshow(np.abs(Corr), origin="lower", aspect="equal")
    axes[1].set_title(r"$|\mathrm{Corr}|$"); ticks(axes[1], "x"); ticks(axes[1], "y")
    fig.colorbar(im, ax=axes[1], fraction=0.045, pad=0.04)
    axes[2].bar(["offdiag Cov", "offdiag Corr", "eff rank"], [offdiag_ratio(Cov), offdiag_ratio(Corr), effective_rank_psd(Cov)])
    axes[2].tick_params(axis="x", rotation=20)
    axes[2].set_title("Summary metrics")
    fig.suptitle(title)
    fig.tight_layout(); fig.savefig(out_dir / "exact_covariance_summary.png", dpi=220); plt.close(fig)
    made.append("exact_covariance_summary.png")
    return made


def save_matrix_csv(path: Path, omegas: np.ndarray, A: np.ndarray) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["omega\\omega_prime"] + [int(o) for o in omegas])
        for i, om in enumerate(omegas):
            writer.writerow([int(om)] + [complex(A[i, j]) for j in range(len(omegas))])


def parse_period(s: str) -> float:
    ss = str(s).strip().lower().replace(" ", "")
    if ss in ("2pi", "2*pi"):
        return 2.0 * math.pi
    if ss in ("4pi", "4*pi"):
        return 4.0 * math.pi
    return float(s)


def validate_mc(args, omegas: np.ndarray, Cov_exact: np.ndarray, mean_exact: np.ndarray, out_dir: Path) -> Optional[dict]:
    n_samples = int(args.validate_mc_samples)
    if n_samples <= 0:
        return None
    try:
        if args.ansatze_path:
            sys.path.insert(0, str(Path(args.ansatze_path).expanduser().resolve()))
        from ansatze import CircuitSpec, build_qnode  # type: ignore
        import jax  # type: ignore
        import jax.numpy as jnp  # type: ignore
    except Exception as exc:
        (out_dir / "mc_validation_error.txt").write_text(f"Import failed: {exc}\n", encoding="utf-8")
        return {"status": "import_failed", "error": str(exc)}

    try:
        spec = CircuitSpec(
            ansatz=args.ansatz,
            n_qubits=args.n_qubits,
            n_layers=args.n_layers,
            train_depth=args.train_depth,
            encoder_axis=args.encoder_axis,
            encoder_scale=float(args.encoder_scale),
            obs_kind=args.obs_kind,
            device_name="default.qubit",
            diff_method="backprop",
            jit=True,
        )
        qnode, m = build_qnode(spec)
        f_vmap_x = jax.jit(jax.vmap(qnode, in_axes=(0, None)))
        rng = np.random.default_rng(int(args.seed) + 104729)
        x = np.linspace(0.0, 2.0 * np.pi, int(args.n_x_mc), endpoint=False)
        Phi = np.exp(-1j * np.outer(omegas.astype(float), x)) / float(len(x))
        A = np.zeros((n_samples, len(omegas)), dtype=np.complex128)
        batch = int(args.mc_batch_size)
        done = 0
        t0 = time.time()
        while done < n_samples:
            b = min(batch, n_samples - done)
            thetas = rng.uniform(0.0, parse_period(args.theta_period), size=(b, int(m)))
            for j in range(b):
                y = np.asarray(f_vmap_x(jnp.asarray(x), jnp.asarray(thetas[j])), dtype=np.float64)
                A[done + j, :] = Phi @ y
            done += b
            if args.progress:
                elapsed = time.time() - t0
                rate = done / max(elapsed, 1e-12)
                eta = (n_samples - done) / max(rate, 1e-12)
                print(
                    f"MC validation {done}/{n_samples} "
                    f"rate={rate:.2f} samples/s "
                    f"elapsed={_fmt_seconds(elapsed)} eta={_fmt_seconds(eta)}",
                    flush=True,
                )
        mean_mc = np.mean(A, axis=0)
        Ac = A - mean_mc[None, :]
        Cov_mc = (Ac.T @ Ac.conj()) / float(n_samples)
        np.savez_compressed(out_dir / "mc_validation.npz", omegas=omegas, mean_mc=mean_mc, Cov_mc=Cov_mc, mean_exact=mean_exact, Cov_exact=Cov_exact)
        save_matrix_csv(out_dir / "mc_covariance.csv", omegas, Cov_mc)
        rel_frob = float(np.linalg.norm(Cov_exact - Cov_mc) / max(1e-15, np.linalg.norm(Cov_mc)))
        align = float(np.real(np.vdot(Cov_exact, Cov_mc)) / max(1e-15, np.linalg.norm(Cov_exact) * np.linalg.norm(Cov_mc)))
        mean_err = float(np.linalg.norm(mean_exact - mean_mc) / max(1e-15, np.linalg.norm(mean_mc)))
        return {"status": "ok", "n_samples": n_samples, "n_x": int(args.n_x_mc), "relative_frobenius_cov": rel_frob, "frobenius_alignment_cov": align, "relative_mean_error": mean_err, "npz": "mc_validation.npz"}
    except Exception as exc:
        (out_dir / "mc_validation_error.txt").write_text(f"Validation failed: {exc}\n", encoding="utf-8")
        return {"status": "failed", "error": str(exc)}


