@dataclass(frozen=True)
class Operation:
    kind: str                         # rot, cnot, cz, cr
    pauli: Optional[int] = None        # for Pauli rotations
    var_kind: Optional[str] = None     # x or theta for rot; theta for cr
    var_index: Optional[int] = None
    omega_scale: int = 1
    wires: Tuple[int, ...] = ()        # cnot/cz: (a,b), cr: (control,target)
    axis: Optional[str] = None         # cr axis: RX or RZ


def params_per_train_block(ansatz: str, n: int) -> int:
    if ansatz in ("YZY", "YZY_ENTANGLING", "HEA", "CIRCUIT_MULTIOBS", "CIRCUIT_ENTFIRST"):
        return 3 * n
    if ansatz == "CIRCUIT_15":
        return 2 * n
    if ansatz in ("CIRCUIT_16", "CIRCUIT_17"):
        return 2 * n + (n - 1)
    if ansatz in ("CIRCUIT_18", "CIRCUIT_19"):
        return 3 * n
    if ansatz == "CIRCUIT_ZZ":
        return 2 * n + n // 2
    raise ValueError(f"Unsupported ansatz for exact covariance: {ansatz}")


def add_rot(ops: List[Operation], n: int, axis: str, wire: int, var_kind: str, var_index: Optional[int] = None, omega_scale: int = 1) -> None:
    ops.append(Operation("rot", pauli=pauli_on(n, axis, wire), var_kind=var_kind, var_index=var_index, omega_scale=int(omega_scale)))


def add_cnot_ring(ops: List[Operation], n: int) -> None:
    for i in range(0, n - 1, 2):
        ops.append(Operation("cnot", wires=(i, i + 1)))
    for i in range(1, n - 1, 2):
        ops.append(Operation("cnot", wires=(i, i + 1)))
    if n > 2:
        ops.append(Operation("cnot", wires=(n - 1, 0)))


def add_cnot_all_to_all(ops: List[Operation], n: int) -> None:
    for i in range(n - 1):
        for j in range(i + 1, n):
            ops.append(Operation("cnot", wires=(i, j)))


def strobl_controlled_pairs(ansatz: str, n: int) -> List[Tuple[int, int]]:
    """Return (control, target) pairs for the corrected circuit 16--19 convention.

    For n=4:
      C16/17: (1->0), (3->2), (2->1)      open neighbouring pattern
      C18/19: (3->0), (2->3), (1->2), (0->1) full ring
    """
    if n < 2:
        raise ValueError("Controlled Strobl circuits require n>=2")
    if ansatz in ("CIRCUIT_16", "CIRCUIT_17"):
        targets = [0] + list(range(n - 2, 0, -1))
        return [(t + 1, t) for t in targets]
    if ansatz in ("CIRCUIT_18", "CIRCUIT_19"):
        targets = [0] + list(range(n - 1, 0, -1))
        return [((t - 1) % n, t) for t in targets]
    raise ValueError(ansatz)


def build_forward_ops(ansatz: str, n: int, L: int, d: int, encoder_axis: str, encoder_scale: int) -> Tuple[List[Operation], int]:
    p_block = params_per_train_block(ansatz, n)
    m = L * d * p_block
    ops: List[Operation] = []
    theta_base = 0
    for _layer in range(L):
        for w in range(n):
            add_rot(ops, n, encoder_axis, w, "x", None, encoder_scale)
        for _block in range(d):
            t0 = theta_base
            if ansatz == "YZY":
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + 0)
                    add_rot(ops, n, "RZ", w, "theta", idx + 1)
                    add_rot(ops, n, "RY", w, "theta", idx + 2)
                    idx += 3
            elif ansatz == "YZY_ENTANGLING":
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + 0)
                    add_rot(ops, n, "RZ", w, "theta", idx + 1)
                    add_rot(ops, n, "RY", w, "theta", idx + 2)
                    idx += 3
                add_cnot_all_to_all(ops, n)
            elif ansatz == "HEA":
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + 0)
                    add_rot(ops, n, "RZ", w, "theta", idx + 1)
                    add_rot(ops, n, "RY", w, "theta", idx + 2)
                    idx += 3
                add_cnot_ring(ops, n)
            elif ansatz == "CIRCUIT_15":
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx); idx += 1
                add_cnot_ring(ops, n)
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx); idx += 1
                add_cnot_ring(ops, n)
            elif ansatz in ("CIRCUIT_16", "CIRCUIT_17", "CIRCUIT_18", "CIRCUIT_19"):
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RX", w, "theta", idx + 0)
                    add_rot(ops, n, "RZ", w, "theta", idx + 1)
                    idx += 2
                cr_axis = "RZ" if ansatz in ("CIRCUIT_16", "CIRCUIT_18") else "RX"
                for control, target in strobl_controlled_pairs(ansatz, n):
                    ops.append(Operation("cr", var_kind="theta", var_index=idx, wires=(control, target), axis=cr_axis))
                    idx += 1
                if idx != t0 + p_block:
                    raise RuntimeError(f"Internal parameter count mismatch for {ansatz}: consumed {idx-t0}, expected {p_block}")
            elif ansatz == "CIRCUIT_ZZ":
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + w)
                idx += n
                for pair in range(n // 2):
                    ops.append(Operation("rot", pauli=pauli_zz(n, 2 * pair, 2 * pair + 1), var_kind="theta", var_index=idx + pair))
                idx += n // 2
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + w)
            elif ansatz == "CIRCUIT_MULTIOBS":
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + 0)
                    add_rot(ops, n, "RZ", w, "theta", idx + 1)
                    add_rot(ops, n, "RY", w, "theta", idx + 2)
                    idx += 3
            elif ansatz == "CIRCUIT_ENTFIRST":
                add_cnot_ring(ops, n)
                idx = t0
                for w in range(n):
                    add_rot(ops, n, "RY", w, "theta", idx + 0)
                    add_rot(ops, n, "RZ", w, "theta", idx + 1)
                    add_rot(ops, n, "RY", w, "theta", idx + 2)
                    idx += 3
            else:
                raise ValueError(ansatz)
            theta_base += p_block
    return ops, m


